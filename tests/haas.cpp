std::vector<Point> lattice_points(int delta) {
  std::vector<Point> pts;
  for (int y = 0; y <= delta; ++y)
    for (int x = 0; x <= delta - y; ++x) pts.push_back({x, y});
  return pts;
}

std::vector<bool> harnack(int delta) {
  std::vector<bool> out;
  for (const Point& p : lattice_points(delta))
    out.push_back(((p.first + 1) * (p.second + 1)) % 2);
  return out;
}

std::vector<bool> from_string(const char* s) {
  std::vector<bool> out;
  for (; *s; ++s) out.push_back(*s == '1');
  return out;
}

Point parity(const Point& p) { return {p.first % 2, p.second % 2}; }

// Row-major-in-y flat index, matching signs_from_splits.
int fidx(int delta, const Point& p) {
  return p.second * (delta + 1) - p.second * (p.second - 1) / 2 + p.first;
}

bool is_unimodular(int delta, const std::vector<Isotopy::Triangle>& tris) {
  if (static_cast<int>(tris.size()) != delta * delta) return false;
  for (const auto& t : tris) {
    auto [xa, ya] = Isotopy::idx_to_point(delta, t[0]);
    auto [xb, yb] = Isotopy::idx_to_point(delta, t[1]);
    auto [xc, yc] = Isotopy::idx_to_point(delta, t[2]);
    if (std::abs((xb - xa) * (yc - ya) - (yb - ya) * (xc - xa)) != 1)
      return false;
  }
  return true;
}

std::set<Isotopy::Edge> edge_set(const std::vector<Isotopy::Triangle>& tris) {
  std::set<Isotopy::Edge> out;
  for (const auto& t : tris)
    for (int a = 0; a < 3; ++a)
      for (int b = a + 1; b < 3; ++b)
        out.insert({std::min(t[a], t[b]), std::max(t[a], t[b])});
  return out;
}

